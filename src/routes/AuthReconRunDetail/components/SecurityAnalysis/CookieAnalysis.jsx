import React, { useState } from 'react'
import Card from '../../../../components/Card'
import Badge from '../../../../components/Badge'
import { Shield, AlertTriangle, Check, X, ChevronDown, ChevronUp, Copy, Download } from 'lucide-react'

function CookieAnalysis({ cookieData }) {
  const [expandedCookies, setExpandedCookies] = useState(new Set())
  const [copiedCookie, setCopiedCookie] = useState(null)
  if (!cookieData) {
    return (
      <Card padding="lg" className="border-slate-700/50">
        <div className="text-center py-8">
          <p className="text-sm text-slate-400">No cookie data available</p>
        </div>
      </Card>
    )
  }

  const {
    cookies = [],
    total_count,
    session_count,
    persistent_count,
    security_score,
    issues = [],
  } = cookieData

  const getScoreVariant = (score) => {
    if (score >= 80) return 'success'
    if (score >= 60) return 'warning'
    return 'error'
  }

  const getEntropyColor = (entropy) => {
    if (!entropy) return 'text-slate-500'
    if (entropy >= 0.8) return 'text-emerald-400'
    if (entropy >= 0.7) return 'text-yellow-400'
    return 'text-rose-400'
  }

  const formatTTL = (ttlSeconds) => {
    if (!ttlSeconds || ttlSeconds <= 0) return 'Session'

    const days = Math.floor(ttlSeconds / 86400)
    const hours = Math.floor((ttlSeconds % 86400) / 3600)

    if (days > 365) {
      const years = Math.floor(days / 365)
      return `${years}yr ${days % 365}d`
    }
    if (days > 0) {
      return hours > 0 ? `${days}d ${hours}h` : `${days}d`
    }
    if (hours > 0) {
      return `${hours}h`
    }
    const minutes = Math.floor(ttlSeconds / 60)
    return `${minutes}m`
  }

  const formatExpires = (expiresAt, maxAge) => {
    if (!expiresAt && !maxAge) return 'Session'
    if (expiresAt) {
      const date = new Date(expiresAt)
      return date.toLocaleDateString()
    }
    if (maxAge) {
      const hours = Math.floor(maxAge / 3600)
      if (hours < 24) return `${hours}h`
      const days = Math.floor(hours / 24)
      return `${days}d`
    }
    return 'Session'
  }

  const toggleCookie = (index) => {
    const newExpanded = new Set(expandedCookies)
    if (newExpanded.has(index)) {
      newExpanded.delete(index)
    } else {
      newExpanded.add(index)
    }
    setExpandedCookies(newExpanded)
  }

  const copyToClipboard = async (text, cookieIndex) => {
    try {
      await navigator.clipboard.writeText(text)
      setCopiedCookie(cookieIndex)
      setTimeout(() => setCopiedCookie(null), 2000)
    } catch (err) {
      console.error('Failed to copy:', err)
    }
  }

  const exportCookiesJSON = () => {
    const json = JSON.stringify(cookies, null, 2)
    const blob = new Blob([json], { type: 'application/json' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = 'cookies.json'
    a.click()
    URL.revokeObjectURL(url)
  }

  const exportCookiesNetscape = () => {
    // Netscape cookie format for curl/wget
    let netscape = '# Netscape HTTP Cookie File\n'
    netscape += '# This file was generated by AuthRecon Suite\n\n'
    cookies.forEach(cookie => {
      const domain = cookie.domain || 'localhost'
      const flag = domain.startsWith('.') ? 'TRUE' : 'FALSE'
      const path = cookie.path || '/'
      const secure = cookie.secure ? 'TRUE' : 'FALSE'
      const expiration = cookie.expires_at ? Math.floor(new Date(cookie.expires_at).getTime() / 1000) : '0'
      const name = cookie.name || ''
      const value = cookie.value_encrypted || ''
      netscape += `${domain}\t${flag}\t${path}\t${secure}\t${expiration}\t${name}\t${value}\n`
    })
    const blob = new Blob([netscape], { type: 'text/plain' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = 'cookies.txt'
    a.click()
    URL.revokeObjectURL(url)
  }

  return (
    <div className="space-y-4">
      {/* Score Card */}
      <Card padding="lg" className="border-slate-700/50">
        <div className="flex items-center justify-between mb-6">
          <div>
            <h3 className="text-lg font-semibold text-slate-50 mb-1">Cookie Security Analysis</h3>
            <p className="text-sm text-slate-400">
              {total_count} cookie{total_count !== 1 ? 's' : ''} detected
              ({session_count} session, {persistent_count} persistent)
            </p>
          </div>
          <div className="text-right">
            <div className="text-3xl font-bold text-slate-50 mb-1">{Math.round(security_score)}/100</div>
            <Badge variant={getScoreVariant(security_score)}>
              {security_score >= 80 ? 'Good' : security_score >= 60 ? 'Fair' : 'Poor'}
            </Badge>
          </div>
        </div>

        {/* Issues */}
        {issues.length > 0 && (
          <div className="space-y-2">
            <div className="flex items-center gap-2 text-sm text-slate-400 mb-3">
              <AlertTriangle className="w-4 h-4" />
              <span className="font-medium">Security Issues Found</span>
            </div>
            <div className="space-y-2">
              {issues.map((issue, idx) => (
                <div key={idx} className="flex items-start gap-2 text-sm">
                  <X className="w-4 h-4 text-rose-400 mt-0.5 flex-shrink-0" />
                  <span className="text-slate-300">{issue}</span>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Export Buttons */}
        {cookies.length > 0 && (
          <div className="flex gap-2 mt-4 pt-4 border-t border-slate-700/30">
            <button
              onClick={exportCookiesJSON}
              className="flex items-center gap-2 px-3 py-1.5 text-xs bg-slate-700/30 hover:bg-slate-700/50 text-slate-300 rounded transition-colors"
            >
              <Download className="w-3 h-3" />
              Export JSON
            </button>
            <button
              onClick={exportCookiesNetscape}
              className="flex items-center gap-2 px-3 py-1.5 text-xs bg-slate-700/30 hover:bg-slate-700/50 text-slate-300 rounded transition-colors"
            >
              <Download className="w-3 h-3" />
              Export Netscape (curl/wget)
            </button>
          </div>
        )}
      </Card>

      {/* Cookie Table */}
      <Card padding="none" className="border-slate-700/50">
        <div className="overflow-x-auto">
          <table className="w-full">
            <thead>
              <tr className="border-b border-slate-700/50 bg-slate-800/30">
                <th className="text-left text-xs font-semibold text-slate-400 uppercase tracking-wider px-4 py-3">
                  Name
                </th>
                <th className="text-left text-xs font-semibold text-slate-400 uppercase tracking-wider px-4 py-3">
                  Domain
                </th>
                <th className="text-center text-xs font-semibold text-slate-400 uppercase tracking-wider px-4 py-3">
                  Secure
                </th>
                <th className="text-center text-xs font-semibold text-slate-400 uppercase tracking-wider px-4 py-3">
                  HttpOnly
                </th>
                <th className="text-center text-xs font-semibold text-slate-400 uppercase tracking-wider px-4 py-3">
                  SameSite
                </th>
                <th className="text-center text-xs font-semibold text-slate-400 uppercase tracking-wider px-4 py-3">
                  Entropy
                </th>
                <th className="text-left text-xs font-semibold text-slate-400 uppercase tracking-wider px-4 py-3">
                  TTL
                </th>
                <th className="text-right text-xs font-semibold text-slate-400 uppercase tracking-wider px-4 py-3">
                  Size
                </th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-700/30">
              {cookies.map((cookie, idx) => {
                const isExpanded = expandedCookies.has(idx)
                const cookieValue = cookie.value_encrypted || ''
                const isCopied = copiedCookie === idx

                return (
                  <React.Fragment key={idx}>
                    <tr
                      className="hover:bg-slate-800/20 transition-colors cursor-pointer"
                      onClick={() => toggleCookie(idx)}
                    >
                      <td className="px-4 py-3">
                        <div className="flex items-center gap-2">
                          {isExpanded ? (
                            <ChevronUp className="w-4 h-4 text-slate-400" />
                          ) : (
                            <ChevronDown className="w-4 h-4 text-slate-400" />
                          )}
                          <Shield className="w-4 h-4 text-slate-500" />
                          <span className="text-sm font-mono text-slate-200">{cookie.name}</span>
                        </div>
                      </td>
                      <td className="px-4 py-3">
                        <span className="text-sm text-slate-400">{cookie.domain}</span>
                      </td>
                      <td className="px-4 py-3 text-center">
                        {cookie.secure ? (
                          <Check className="w-4 h-4 text-emerald-400 mx-auto" />
                        ) : (
                          <X className="w-4 h-4 text-rose-400 mx-auto" />
                        )}
                      </td>
                      <td className="px-4 py-3 text-center">
                        {cookie.http_only ? (
                          <Check className="w-4 h-4 text-emerald-400 mx-auto" />
                        ) : (
                          <X className="w-4 h-4 text-rose-400 mx-auto" />
                        )}
                      </td>
                      <td className="px-4 py-3 text-center">
                        <span className="text-xs text-slate-300">{cookie.same_site || 'None'}</span>
                      </td>
                      <td className="px-4 py-3 text-center">
                        {cookie.entropy !== null && cookie.entropy !== undefined ? (
                          <span className={`text-sm font-mono ${getEntropyColor(cookie.entropy)}`}>
                            {cookie.entropy.toFixed(2)}
                          </span>
                        ) : (
                          <span className="text-sm text-slate-500">N/A</span>
                        )}
                      </td>
                      <td className="px-4 py-3">
                        <span className="text-xs text-slate-400">
                          {formatTTL(cookie.ttl_seconds)}
                        </span>
                      </td>
                      <td className="px-4 py-3 text-right">
                        <span className="text-xs text-slate-500">{cookie.size_bytes}B</span>
                      </td>
                    </tr>
                    {isExpanded && (
                      <tr className="bg-slate-800/10">
                        <td colSpan="8" className="px-4 py-4">
                          <div className="space-y-3">
                            {/* Cookie Value */}
                            <div>
                              <div className="flex items-center justify-between mb-2">
                                <span className="text-xs font-semibold text-slate-400 uppercase tracking-wider">Value</span>
                                <button
                                  onClick={(e) => {
                                    e.stopPropagation()
                                    copyToClipboard(cookieValue, idx)
                                  }}
                                  className="flex items-center gap-1 px-2 py-1 text-xs bg-slate-700/30 hover:bg-slate-700/50 text-slate-300 rounded transition-colors"
                                >
                                  <Copy className="w-3 h-3" />
                                  {isCopied ? 'Copied!' : 'Copy'}
                                </button>
                              </div>
                              <div className="bg-slate-950/50 rounded border border-slate-800 p-3">
                                <code className="text-xs text-slate-300 font-mono break-all">
                                  {cookieValue || '(empty)'}
                                </code>
                              </div>
                            </div>

                            {/* Full Details */}
                            <div className="grid grid-cols-2 md:grid-cols-3 gap-3 text-xs">
                              <div>
                                <span className="text-slate-500">Path:</span>
                                <span className="ml-2 text-slate-300">{cookie.path || '/'}</span>
                              </div>
                              {cookie.expires_at && (
                                <div>
                                  <span className="text-slate-500">Expires:</span>
                                  <span className="ml-2 text-slate-300">
                                    {new Date(cookie.expires_at).toLocaleString()}
                                  </span>
                                </div>
                              )}
                              {cookie.max_age && (
                                <div>
                                  <span className="text-slate-500">Max-Age:</span>
                                  <span className="ml-2 text-slate-300">{cookie.max_age}s</span>
                                </div>
                              )}
                            </div>
                          </div>
                        </td>
                      </tr>
                    )}
                  </React.Fragment>
                )
              })}
            </tbody>
          </table>
        </div>
      </Card>
    </div>
  )
}

export default CookieAnalysis
