"""
curl Command Export Module

Generates curl commands for replaying authentication flows.
"""
from __future__ import annotations

import shlex
from typing import List, Dict, Any, Optional
from urllib.parse import urlparse


def export_to_curl(
    final_url: str,
    cookies: List[str],
    recorded_actions: List[Dict[str, Any]],
    *,
    username_placeholder: str = "YOUR_USERNAME",
    password_placeholder: str = "YOUR_PASSWORD",
    form_action_url: Optional[str] = None,
    method: str = "POST",
    include_cookies: bool = True,
    follow_redirects: bool = True,
) -> str:
    """
    Export authentication flow as a curl command.

    Args:
        final_url: The final authenticated URL
        cookies: List of cookie names from successful auth
        recorded_actions: List of actions recorded during automation
        username_placeholder: Placeholder for username
        password_placeholder: Placeholder for password
        form_action_url: Form action URL (defaults to final_url)
        method: HTTP method (POST, GET, etc.)
        include_cookies: Whether to include --cookie flag
        follow_redirects: Whether to add -L flag

    Returns:
        curl command string
    """

    target_url = form_action_url or final_url
    parsed = urlparse(target_url)

    # Build form data from recorded actions
    form_data = []
    for action in recorded_actions:
        if action.get("action") == "type":
            selector = action.get("selector", "")
            value = action.get("value", "")

            # Extract field name
            field_name = _extract_field_name_from_selector(selector)
            if field_name:
                # Replace placeholders with user-friendly values
                actual_value = value
                if "${USERNAME}" in value:
                    actual_value = username_placeholder
                elif "${PASSWORD}" in value:
                    actual_value = password_placeholder

                form_data.append((field_name, actual_value))

    # Build curl command
    parts = ["curl"]

    # Add method if not GET
    if method.upper() != "GET":
        parts.extend(["-X", method.upper()])

    # Add headers
    parts.extend([
        "-H", "'User-Agent: Mozilla/5.0 (AuthRecon Security Scanner)'",
        "-H", "'Accept: text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8'",
        "-H", "'Content-Type: application/x-www-form-urlencoded'",
        "-H", f"'Origin: {parsed.scheme}://{parsed.netloc}'",
        "-H", f"'Referer: {target_url}'",
    ])

    # Add cookies if captured
    if include_cookies and cookies:
        cookie_pairs = [f"{name}=CAPTURED_VALUE" for name in cookies]
        cookie_string = "; ".join(cookie_pairs)
        parts.extend(["-H", f"'Cookie: {cookie_string}'"])

    # Add form data
    for field_name, field_value in form_data:
        # Properly escape the values for shell
        parts.extend(["-d", f"'{field_name}={field_value}'"])

    # Add follow redirects flag
    if follow_redirects:
        parts.append("-L")

    # Add the URL
    parts.append(f"'{target_url}'")

    return " \\\n  ".join(parts)


def export_to_curl_script(
    final_url: str,
    cookies: List[str],
    recorded_actions: List[Dict[str, Any]],
    *,
    username_var: str = "USERNAME",
    password_var: str = "PASSWORD",
    form_action_url: Optional[str] = None,
) -> str:
    """
    Export as a complete bash script with variables.

    This creates a more user-friendly script that can be easily modified.

    Returns:
        Bash script with curl command and variable placeholders
    """

    target_url = form_action_url or final_url

    # Build form data extraction
    form_data = []
    for action in recorded_actions:
        if action.get("action") == "type":
            selector = action.get("selector", "")
            value = action.get("value", "")
            field_name = _extract_field_name_from_selector(selector)

            if field_name:
                if "${USERNAME}" in value:
                    form_data.append((field_name, f"${{{username_var}}}"))
                elif "${PASSWORD}" in value:
                    form_data.append((field_name, f"${{{password_var}}}"))
                else:
                    form_data.append((field_name, value))

    # Build script
    lines = [
        "#!/bin/bash",
        "# AuthRecon - Authentication Test Script",
        "# Generated by AuthRecon Security Scanner",
        "",
        "# Configuration",
        f'{username_var}="YOUR_USERNAME_HERE"',
        f'{password_var}="YOUR_PASSWORD_HERE"',
        f'TARGET_URL="{target_url}"',
        "",
        "# Execute authentication request",
        "curl -X POST \\",
        "  -H 'User-Agent: Mozilla/5.0 (AuthRecon)' \\",
        "  -H 'Accept: text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8' \\",
        "  -H 'Content-Type: application/x-www-form-urlencoded' \\",
    ]

    # Add form data
    for field_name, field_value in form_data:
        lines.append(f"  -d '{field_name}={field_value}' \\")

    # Add final line
    lines.append("  -L \\")
    lines.append('  "$TARGET_URL"')
    lines.append("")
    lines.append("# End of script")

    return "\n".join(lines)


def _extract_field_name_from_selector(selector: str) -> Optional[str]:
    """Extract field name from CSS selector."""
    if not selector:
        return None

    selector = selector.replace("css=", "").strip()

    # Try [name='...']
    if "[name=" in selector:
        start = selector.index("[name=") + 6
        if selector[start] in ("'", '"'):
            quote = selector[start]
            start += 1
            try:
                end = selector.index(quote, start)
                return selector[start:end]
            except ValueError:
                pass

    # Try #id
    if "#" in selector:
        id_part = selector.split("#")[1].split("[")[0].split(".")[0].split(":")[0]
        return id_part

    return None
